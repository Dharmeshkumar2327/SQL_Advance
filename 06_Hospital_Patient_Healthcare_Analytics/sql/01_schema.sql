-- 01_schema.sql
-- PostgreSQL 14+ | Run in a dedicated project database.
DROP VIEW IF EXISTS vw_monthly_hospital_kpis CASCADE;
DROP VIEW IF EXISTS vw_patient_financial_summary CASCADE;
DROP VIEW IF EXISTS vw_admission_details CASCADE;
DROP TABLE IF EXISTS payments, diagnoses, admissions, beds, doctors, patients, departments CASCADE;

CREATE TABLE departments (
    department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(80) NOT NULL UNIQUE,
    floor_no INT NOT NULL CHECK (floor_no >= 0)
);

CREATE TABLE doctors (
    doctor_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_name VARCHAR(100) NOT NULL,
    specialization VARCHAR(80) NOT NULL,
    department_id INT NOT NULL REFERENCES departments(department_id),
    hire_date DATE NOT NULL
);

CREATE TABLE patients (
    patient_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(20) NOT NULL CHECK (gender IN ('Female','Male','Other','Prefer not to say')),
    city VARCHAR(80) NOT NULL,
    registration_date DATE NOT NULL
);

CREATE TABLE beds (
    bed_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_name VARCHAR(60) NOT NULL,
    bed_type VARCHAR(30) NOT NULL CHECK (bed_type IN ('General','Private','ICU')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE admissions (
    admission_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    doctor_id INT NOT NULL REFERENCES doctors(doctor_id),
    bed_id INT REFERENCES beds(bed_id),
    admission_date DATE NOT NULL,
    discharge_date DATE,
    admission_type VARCHAR(20) NOT NULL CHECK (admission_type IN ('Emergency','Elective','Urgent')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('Discharged','Admitted','Transferred')),
    billed_amount NUMERIC(12,2) NOT NULL CHECK (billed_amount >= 0),
    CHECK (discharge_date IS NULL OR discharge_date >= admission_date),
    CHECK ((status = 'Admitted' AND discharge_date IS NULL) OR status <> 'Admitted')
);

CREATE TABLE diagnoses (
    diagnosis_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id INT NOT NULL REFERENCES admissions(admission_id) ON DELETE CASCADE,
    diagnosis_code VARCHAR(12) NOT NULL,
    diagnosis_name VARCHAR(100) NOT NULL,
    diagnosis_category VARCHAR(60) NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE payments (
    payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id INT NOT NULL REFERENCES admissions(admission_id) ON DELETE CASCADE,
    payment_date DATE NOT NULL,
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('Cash','Card','UPI','Insurance','Bank Transfer')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    payment_status VARCHAR(20) NOT NULL CHECK (payment_status IN ('Completed','Pending','Refunded'))
);
